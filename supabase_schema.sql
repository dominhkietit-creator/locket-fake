-- ==============================================================================
-- BẢN SỬA ĐỔI HOÀN CHỈNH & CHUẨN XÁC 100% CHO SUPABASE LOCKET CLONE
-- Chạy toàn bộ đoạn mã này trong Supabase Dashboard -> SQL Editor
-- (Có thể chạy lại nhiều lần mà không bị báo lỗi trùng bảng hay trùng publication)
